import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';

const dash = readFileSync(new URL('../src/auth/SuperAdminDashboard.jsx', import.meta.url), 'utf8');
const admin = readFileSync(new URL('../src/auth/WalletsAdmin.jsx', import.meta.url), 'utf8');
const list = readFileSync(new URL('../src/auth/wallets/WalletsListPage.jsx', import.meta.url), 'utf8');
const detail = readFileSync(new URL('../src/auth/wallets/WalletDetailPage.jsx', import.meta.url), 'utf8');
const adjust = readFileSync(new URL('../src/auth/wallets/WalletAdjustPage.jsx', import.meta.url), 'utf8');
const entry = readFileSync(new URL('../src/auth/wallets/WalletEntryPage.jsx', import.meta.url), 'utf8');
const filtersMenu = readFileSync(new URL('../src/auth/FiltersMenu.jsx', import.meta.url), 'utf8');
const api = readFileSync(new URL('../src/utils/api.js', import.meta.url), 'utf8');

test('library wallets is a super admin tab with the shared page kit', () => {
  assert.match(dash, /id="sa-tab-wallets"/);
  assert.match(dash, /Library wallets/);
  assert.match(dash, /WalletsAdmin/);
  assert.match(list, /id="sa-wallets"/);
  assert.match(list, /sa-wallets-filters-button/);
  assert.match(list, /sa-wallets-filters-menu/);
  assert.match(list, /FiltersMenu/);
  assert.match(list, /DatePeriodSelect/);
  assert.match(list, /id="sa-wallets-filters-period"/);
  assert.match(list, /preset: 'all_time'/);
  assert.match(list, /!== 'all_time'/);
  const period = list.lastIndexOf('<DatePeriodSelect');
  assert.ok(period > list.indexOf('filters-menu'));
  assert.ok(period < list.indexOf('<select', period));
  assert.doesNotMatch(list, /PERIODS\.map/);
  assert.doesNotMatch(list, /aria-pressed/);
  assert.match(filtersMenu, /<select id=\{id\}/);
  assert.match(detail, /id="sa-wallet-detail"/);
  assert.match(adjust, /id="sa-wallet-adjust"/);
  assert.match(entry, /id="sa-wallet-entry"/);
  for (const file of [list, detail, adjust, entry]) {
    assert.match(file, /SaPage/);
    assert.match(file, /SaPageHeader/);
    assert.match(file, /onBack|Library wallets/);
  }
  assert.match(detail, /SaRecordHero/);
  assert.match(detail, /SaRecordTimeline/);
  assert.match(detail, /SaRecordSection/);
  assert.match(detail, /SaMoreInfo/);
  assert.match(detail, /SaHelper/);
  assert.match(detail, /SaRecordActions/);
  assert.match(detail, /Add credit/);
  assert.match(detail, /Deduct credit/);
  assert.match(entry, /SaRecordHero/);
  assert.match(entry, /SaRecordTimeline/);
  assert.match(entry, /SaRecordSection/);
  assert.match(entry, /SaMoreInfo/);
  assert.match(entry, /SaHelper/);
  assert.match(entry, /Paid online/);
  assert.match(entry, /Added by Super Admin/);
  assert.match(entry, /Used on an invoice/);
  assert.match(adjust, /Preview/);
  assert.match(adjust, /Confirm/);
  assert.match(adjust, /Available after/);
  assert.match(adjust, /id="sa-wallet-adjust-preview"/);
  assert.match(adjust, /id="sa-wallet-adjust-confirm"/);
  assert.match(adjust, /Nothing changes until you confirm/);
  assert.doesNotMatch(adjust, /role="dialog"/);
  assert.doesNotMatch(entry, /admin_adjustment|wallet_payment|tenantId/);
  assert.doesNotMatch(detail, /<h[1-6][^>]*>[^<]*(admin_adjustment|wallet_payment|tenantId)/);
  assert.match(admin, /WalletDetailPage/);
  assert.match(admin, /WalletAdjustPage/);
  assert.match(admin, /WalletEntryPage/);
  assert.match(api, /adminWalletPreview/);
  assert.match(api, /adminWalletAdjust/);
  assert.match(api, /Idempotency-Key/);
});
